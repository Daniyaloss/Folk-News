  const DICT = { en: EN, id: ID };
  const AUTH_PAGES = new Set(['welcome', 'login', 'signup']);
  const PAGE = document.body ? document.body.dataset.page : '';
  let lang = 'id';
  try {
    const stored = localStorage.getItem(KEY);
    if (stored === 'en' || stored === 'id') lang = stored;
  } catch {}
  if (AUTH_PAGES.has(PAGE)) lang = 'en';

  const t = (key, vars = {}, fallback = key) => {
    let value = DICT[lang][key] ?? EN[key] ?? fallback;
    for (const [name, replacement] of Object.entries(vars)) value = String(value).split(`{${name}}`).join(replacement);
    return value;
  };

